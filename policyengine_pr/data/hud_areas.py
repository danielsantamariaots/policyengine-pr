def area_of_fips(fips: int) -> str:
    return next(a for m, (f, a) in MUNICIPIOS.items() if f == fips)


def area_of_puma(puma: int) -> str:
    """The HUD area of the PUMA's first-listed municipio with the most
    members in the PUMA's area set (ties: the lowest FIPS). PUMAs that span
    areas (e.g. 1900, 2000, 0700, 0800) are assigned to one area: GAP."""
    areas = [area_of_fips(f) for f in PUMA_MUNICIPIOS[puma]]
    return max(set(areas), key=lambda a: (areas.count(a), -areas.index(a)))
